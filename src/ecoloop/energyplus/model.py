def prepare_models(
    settings: object,
    period: PeriodProtocol,
    source: Path | None = None,
    *,
    output_directory: Path | None = None,
) -> ModelArtifacts:
    """Prepare baseline, agent-ready, and replay-ready IDFs using EnergyPlus tooling.

    ``prepare-model`` uses the canonical repository directory. Runtime callers
    pass a run-local directory so an experiment cannot mutate tracked models.
    """

    installation = require_energyplus(settings, model_tooling=True)
    if installation.schema is None:
        raise EnergyPlusIntegrationError("EnergyPlus schema is required for model preparation.")
    root = repository_root()
    configured_model_method = getattr(settings, "resolved_model_path", None)
    configured_model = (
        configured_model_method()
        if callable(configured_model_method)
        else root / "models" / "base" / "building.idf"
    )
    source_model, provenance = _copy_or_select_source(
        installation,
        Path(configured_model),
        source,
    )
    generated = (
        output_directory.expanduser().resolve()
        if output_directory is not None
        else (root / "models" / "generated").resolve()
    )
    generated.mkdir(parents=True, exist_ok=True)
    schema_data, schema = load_epjson_schema(installation.schema)
    del schema_data

    with tempfile.TemporaryDirectory(prefix="ecoloop-prepare-") as temporary:
        work = Path(temporary)
        source_epjson_path = work / "source.epJSON"
        convert_input_format(installation, source_model, "epJSON", source_epjson_path)
        try:
            source_epjson = json.loads(source_epjson_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise EnergyPlusIntegrationError(
                f"Converted epJSON could not be loaded: {source_epjson_path}: {exc}"
            ) from exc
        if not isinstance(source_epjson, dict):
            raise EnergyPlusIntegrationError("Converted model is not an epJSON object.")

        timestep_minutes = int(getattr(settings, "zone_timestep_minutes", 15))
        baseline_epjson, baseline_metadata = patch_model(
            source_epjson,
            schema,
            period,
            timestep_minutes,
            controlled=False,
        )
        agent_epjson, agent_metadata = patch_model(
            source_epjson,
            schema,
            period,
            timestep_minutes,
            controlled=True,
        )
        baseline_json_path = work / "baseline.epJSON"
        agent_json_path = work / "agent_ready.epJSON"
        _write_json(baseline_json_path, baseline_epjson)
        _write_json(agent_json_path, agent_epjson)
        baseline_idf = generated / "baseline.idf"
        agent_idf = generated / "agent_ready.idf"
        replay_idf = generated / "agent_replay.idf"
        convert_input_format(installation, baseline_json_path, "idf", baseline_idf)
        convert_input_format(installation, agent_json_path, "idf", agent_idf)
        # Replay uses the same verified actuator-capable model. The replay runtime
        # applies the exported schedule without invoking the model host.
        shutil.copy2(agent_idf, replay_idf)

    action_schedule = generated / "action_schedule.csv"
    _empty_action_schedule(action_schedule)
    actuator_map = generated / "actuator_map.csv"
    _write_actuator_map(actuator_map, agent_metadata)
    provenance_path = source_model.parent / "PROVENANCE.json"
    _write_json(
        provenance_path,
        _portable_provenance_payload(provenance, source_model),
    )
    manifest = generated / "preparation-manifest.json"
    _write_json(
        manifest,
        {
            "energyplus_version": installation.version,
            "energyplus_distribution": (
                f"EnergyPlus {installation.version}; installation is discovered locally at runtime"
            ),
            "source_model": _portable_repository_path(source_model),
            "source_model_sha256": _sha256_model_text(source_model),
            "source_model_sha256_mode": "utf-8-text-lf-normalized",
            "period": {
                "start_month": int(period.start_month),
                "start_day": int(period.start_day),
                "end_month": int(period.end_month),
                "end_day": int(period.end_day),
            },
            "baseline": baseline_metadata,
            "agent_ready": agent_metadata,
            "generated_artifacts": {
                "baseline_idf_sha256": _sha256_file(baseline_idf),
                "agent_ready_idf_sha256": _sha256_file(agent_idf),
                "agent_replay_idf_sha256": _sha256_file(replay_idf),
                "actuator_map_sha256": _sha256_file(actuator_map),
            },
            "replay_method": (
                "EnergyPlus Runtime API applies action_schedule.csv to the same discovered "
                "schedule actuators; no local model inference is called."
            ),
            "runtime_electricity_signals": {
                "preferred": "Electricity:Facility",
                "fallback": "ElectricityNet:Facility",
                "note": (
                    "The Runtime API records which handle supplied callback telemetry. "
                    "Official final energy always comes from Electricity:Facility in "
                    "EnergyPlus SQL/CSV and is cross-checked."
                ),
            },
            "timestep_minutes": int(getattr(settings, "zone_timestep_minutes", 15)),
        },
    )
    return ModelArtifacts(
        source_model=source_model,
        baseline_model=baseline_idf,
        agent_ready_model=agent_idf,
        agent_replay_model=replay_idf,
        action_schedule=action_schedule,
        actuator_map=actuator_map,
        provenance=provenance_path,
        preparation_manifest=manifest,
    )


@dataclass(frozen=True, slots=True)
class ReplayAction:
    """One validated applied action exported for deterministic replay."""

    simulation_timestamp: str
    observation_id: int
    action_generation: int
    heating_setpoint_c: float
    cooling_setpoint_c: float
    hold_minutes: int

    def __post_init__(self) -> None:
        for name, value in (
            ("heating_setpoint_c", self.heating_setpoint_c),
            ("cooling_setpoint_c", self.cooling_setpoint_c),
        ):
            if not math.isfinite(value):
                raise ValueError(f"{name} must be finite")
        if self.heating_setpoint_c >= self.cooling_setpoint_c:
            raise ValueError("Replay heating setpoint must be below cooling setpoint")
        if self.observation_id < 1 or self.action_generation < 1 or self.hold_minutes < 1:
            raise ValueError("Replay identifiers and hold duration must be positive")


def write_action_schedule(actions: Iterable[ReplayAction], path: Path) -> Path:
    """Write validated applied actions in deterministic generation order."""

    ordered = sorted(
        actions,
        key=lambda item: (
            item.simulation_timestamp,
            item.action_generation,
            item.observation_id,
        ),
    )
    seen_generations: set[int] = set()
    last_generation = 0
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(
            (
                "simulation_timestamp",
                "observation_id",
                "action_generation",
                "heating_setpoint_c",
                "cooling_setpoint_c",
                "hold_minutes",
            )
        )
        for action in ordered:
            if (
                action.action_generation in seen_generations
                or action.action_generation <= last_generation
            ):
                raise EnergyPlusIntegrationError(
                    f"Replay action generation is duplicate or non-monotonic: "
                    f"{action.action_generation}."
                )
            seen_generations.add(action.action_generation)
            last_generation = action.action_generation
            writer.writerow(
                (
                    action.simulation_timestamp,
                    action.observation_id,
                    action.action_generation,
                    format(action.heating_setpoint_c, ".6f"),
                    format(action.cooling_setpoint_c, ".6f"),
                    action.hold_minutes,
                )
            )
    return path
