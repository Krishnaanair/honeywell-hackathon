class SchemaNavigator:
    """Look up object and field definitions in the installed EnergyPlus schema."""

    def __init__(self, schema: Mapping[str, Any]) -> None:
        self._schema = schema

    def _resolve(self, value: Mapping[str, Any]) -> Mapping[str, Any]:
        reference = value.get("$ref")
        if not isinstance(reference, str):
            return value
        if not reference.startswith("#/"):
            raise EnergyPlusIntegrationError(f"Unsupported external schema reference: {reference}")
        current: Any = self._schema
        for part in reference[2:].split("/"):
            current = current[part.replace("~1", "/").replace("~0", "~")]
        if not isinstance(current, Mapping):
            raise EnergyPlusIntegrationError(f"Schema reference is not an object: {reference}")
        return self._resolve(current)

    def object_schema(self, object_type: str) -> Mapping[str, Any]:
        """Return the schema for one epJSON object instance."""

        properties = self._schema.get("properties")
        if not isinstance(properties, Mapping) or object_type not in properties:
            raise EnergyPlusIntegrationError(
                f"EnergyPlus 26.1 schema does not define object type {object_type!r}."
            )
        container = properties[object_type]
        if not isinstance(container, Mapping):
            raise EnergyPlusIntegrationError(f"Invalid schema container for {object_type!r}.")
        container = self._resolve(container)
        patterns = container.get("patternProperties")
        if isinstance(patterns, Mapping) and patterns:
            pattern_value = next(iter(patterns.values()))
            if isinstance(pattern_value, Mapping):
                return self._resolve(pattern_value)
        additional = container.get("additionalProperties")
        if isinstance(additional, Mapping):
            return self._resolve(additional)
        raise EnergyPlusIntegrationError(
            f"Could not locate instance fields for schema object {object_type!r}."
        )

    def has_object(self, object_type: str) -> bool:
        """Return whether an object type exists in the installed schema."""

        properties = self._schema.get("properties")
        return isinstance(properties, Mapping) and object_type in properties

    def field_names(self, object_type: str) -> frozenset[str]:
        """Return valid field names for an object type."""

        properties = self.object_schema(object_type).get("properties")
        if not isinstance(properties, Mapping):
            return frozenset()
        return frozenset(str(item) for item in properties)

    def require_fields(self, object_type: str, fields: Iterable[str]) -> None:
        """Require fields before modifying a model, preventing guessed field writes."""

        valid = self.field_names(object_type)
        missing = sorted(set(fields) - valid)
        if missing:
            raise EnergyPlusIntegrationError(
                f"EnergyPlus 26.1 schema object {object_type!r} lacks fields: {', '.join(missing)}."
            )

    def validate_instance_fields(self, object_type: str, instance: Mapping[str, Any]) -> None:
        """Reject fields not advertised by the version-matched schema."""

        self.require_fields(object_type, instance.keys())


def load_epjson_schema(path: Path) -> tuple[dict[str, Any], SchemaNavigator]:
    """Load the installed EnergyPlus epJSON schema."""

    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise EnergyPlusIntegrationError(f"Could not load EnergyPlus schema {path}: {exc}") from exc
    if not isinstance(value, dict):
        raise EnergyPlusIntegrationError(f"EnergyPlus schema {path} is not a JSON object.")
    return value, SchemaNavigator(value)


def _read_model_text(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace").casefold()


def score_example_model(path: Path) -> CandidateExample:
    """Score an official example for a fast multi-zone supervisory-control demo."""

    name = path.name.casefold()
    text = _read_model_text(path)
    score = 0
    reasons: list[str] = []
    if "smalloffice" in name:
        score += 40
        reasons.append("small-office example")
    if "5zone" in name or "fivezone" in name:
        score += 35
        reasons.append("five-zone example")
    if text.count("zone,") >= 3:
        score += 20
        reasons.append("multiple zones")
    if "people," in text:
        score += 12
        reasons.append("People objects")
    if "zonectrl:thermostat" in text or "zonecontrol:thermostat" in text:
        score += 12
        reasons.append("zone thermostats")
    if "coil:heating:electric" in text:
        score += 15
        reasons.append("electric heating")
    if "coil:cooling:dx" in text:
        score += 12
        reasons.append("DX cooling")
    if "heatpump" in name or "heat pump" in text:
        score += 15
        reasons.append("heat-pump equipment")
    if "naturalgas" in text or "natural gas" in text:
        score -= 8
        reasons.append("contains non-electric fuel")
    if path.stat().st_size > 2_000_000:
        score -= 20
        reasons.append("large model")
    if "advanced" in name or "benchmark" in name:
        score -= 12
        reasons.append("complex example")
    return CandidateExample(path.resolve(), score, tuple(reasons))


def select_official_example(installation: EnergyPlusInstallation) -> CandidateExample:
    """Select the highest-scoring official version-matched example model."""

    examples = installation.example_files
    if examples is None or not examples.is_dir():
        raise EnergyPlusIntegrationError(
            f"EnergyPlus ExampleFiles were not found below {installation.home}. "
            "Reinstall the complete 26.1.0 distribution or configure an explicit source model."
        )
    candidates = [score_example_model(path) for path in examples.rglob("*.idf") if path.is_file()]
    eligible = [
        item
        for item in candidates
        if "multiple zones" in item.reasons
        and "People objects" in item.reasons
        and "zone thermostats" in item.reasons
    ]
    if not eligible:
        raise EnergyPlusIntegrationError(
            f"No official example under {examples} met the multi-zone/People/thermostat criteria."
        )
    return sorted(eligible, key=lambda item: (-item.score, item.path.name.casefold()))[0]


def _conversion_output(work: Path, stem: str, target_format: str) -> Path | None:
    suffixes = {
        "epJSON": (".epJSON", ".epjson"),
        "idf": (".idf", ".IDF"),
    }[target_format]
    for suffix in suffixes:
        candidate = work / f"{stem}{suffix}"
        if candidate.is_file():
            return candidate
    for candidate in work.iterdir():
        if (
            candidate.is_file()
            and candidate.stem.casefold() == stem.casefold()
            and candidate.suffix.casefold() in {item.casefold() for item in suffixes}
        ):
            return candidate
    return None


def convert_input_format(
    installation: EnergyPlusInstallation,
    source: Path,
    target_format: str,
    destination: Path,
) -> Path:
    """Convert IDF/epJSON using the installed official ConvertInputFormat tool."""

    if target_format not in {"epJSON", "idf"}:
        raise ValueError(f"Unsupported EnergyPlus conversion format: {target_format}")
    tool = installation.convert_input_format
    if tool is None:
        raise EnergyPlusIntegrationError(
            f"ConvertInputFormat was not found below {installation.home}."
        )
    if not source.is_file():
        raise EnergyPlusIntegrationError(f"Model source does not exist: {source}")

    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="ecoloop-convert-") as temporary:
        work = Path(temporary)
        local_source = work / source.name
        shutil.copy2(source, local_source)
        command = [str(tool), "--format", target_format, str(local_source)]
        try:
            completed = subprocess.run(  # noqa: S603 - official tool path is discovered
                command,
                cwd=work,
                capture_output=True,
                check=False,
                text=True,
                timeout=120,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise EnergyPlusIntegrationError(
                f"ConvertInputFormat could not process {source}: {exc}"
            ) from exc
        output = _conversion_output(work, local_source.stem, target_format)
        if completed.returncode != 0 or output is None:
            diagnostic = "\n".join(
                value.strip() for value in (completed.stdout, completed.stderr) if value.strip()
            )
            raise EnergyPlusIntegrationError(
                f"ConvertInputFormat failed for {source} (exit {completed.returncode}). "
                f"Output: {diagnostic or 'no diagnostic output'}"
            )
        shutil.copy2(output, destination)
    return destination


def _instances(model: dict[str, Any], object_type: str) -> dict[str, dict[str, Any]]:
    value = model.setdefault(object_type, {})
    if not isinstance(value, dict):
        raise EnergyPlusIntegrationError(f"epJSON object {object_type!r} is not a mapping.")
    for key, instance in value.items():
        if not isinstance(instance, dict):
            raise EnergyPlusIntegrationError(
                f"epJSON object {object_type!r}/{key!r} is not a mapping."
            )
    return value


def _temperature_type_limit(
    model: dict[str, Any],
    schema: SchemaNavigator,
) -> str:
    object_type = "ScheduleTypeLimits"
    existing = _instances(model, object_type)
    valid_fields = schema.field_names(object_type)
    for name, instance_fields in existing.items():
        unit = instance_fields.get("unit_type")
        if isinstance(unit, str) and unit.casefold() == "temperature":
            return name
    fields: dict[str, Any] = {}
    if "unit_type" in valid_fields:
        fields["unit_type"] = "Temperature"
    if "numeric_type" in valid_fields:
        fields["numeric_type"] = "Continuous"
    schema.validate_instance_fields(object_type, fields)
    existing["EcoLoop Temperature"] = fields
    return "EcoLoop Temperature"


