def _install_baseline_schedules(
    model: dict[str, Any],
    schema: SchemaNavigator,
    *,
    controlled: bool,
) -> tuple[str, str, str, str, int]:
    schedule_type = "Schedule:Compact"
    schema.require_fields(schedule_type, ("schedule_type_limits_name", "data"))
    temperature_limit = _temperature_type_limit(model, schema)
    schedules = _instances(model, schedule_type)

    reference_heating = "EcoLoop Reference Heating Setpoint"
    reference_cooling = "EcoLoop Reference Cooling Setpoint"
    actuated_heating = "EcoLoop Actuated Heating Setpoint"
    actuated_cooling = "EcoLoop Actuated Cooling Setpoint"
    heating = {
        "schedule_type_limits_name": temperature_limit,
        "data": _baseline_schedule_data(20.0, 18.0),
    }
    cooling = {
        "schedule_type_limits_name": temperature_limit,
        "data": _baseline_schedule_data(24.0, 28.0),
    }
    schema.validate_instance_fields(schedule_type, heating)
    schema.validate_instance_fields(schedule_type, cooling)
    schedules[reference_heating] = copy.deepcopy(heating)
    schedules[reference_cooling] = copy.deepcopy(cooling)
    schedules[actuated_heating] = copy.deepcopy(heating)
    schedules[actuated_cooling] = copy.deepcopy(cooling)

    heating_target = actuated_heating if controlled else reference_heating
    cooling_target = actuated_cooling if controlled else reference_cooling
    patched = 0
    for object_type, (heating_field, cooling_field) in _THERMOSTAT_FIELDS.items():
        if not schema.has_object(object_type):
            continue
        fields = tuple(field for field in (heating_field, cooling_field) if field)
        schema.require_fields(object_type, fields)
        for thermostat in _instances(model, object_type).values():
            if heating_field:
                thermostat[heating_field] = heating_target
            if cooling_field:
                thermostat[cooling_field] = cooling_target
            patched += 1
    if patched == 0:
        raise EnergyPlusIntegrationError(
            "The selected model has no supported thermostat setpoint object. "
            "No schedule fields were guessed or rewritten."
        )
    return (
        reference_heating,
        reference_cooling,
        actuated_heating,
        actuated_cooling,
        patched,
    )


def _add_output_variable(
    model: dict[str, Any],
    schema: SchemaNavigator,
    variable_name: str,
    key: str,
    *,
    label: str | None = None,
) -> None:
    object_type = "Output:Variable"
    fields = {
        "key_value": key,
        "variable_name": variable_name,
        "reporting_frequency": "Timestep",
    }
    schema.validate_instance_fields(object_type, fields)
    output = _instances(model, object_type)
    instance_name = label or f"EcoLoop {variable_name} {key}"
    output[instance_name] = fields


def _add_outputs(
    model: dict[str, Any],
    schema: SchemaNavigator,
    reference_schedules: tuple[str, str],
    actuated_schedules: tuple[str, str],
    *,
    include_fanger: bool,
) -> None:
    for variable_name, key in _OUTPUT_VARIABLES:
        _add_output_variable(model, schema, variable_name, key)

    contaminant = model.get("ZoneAirContaminantBalance")
    if isinstance(contaminant, Mapping) and contaminant:
        _add_output_variable(model, schema, "Zone Air CO2 Concentration", "*")
    if include_fanger:
        _add_output_variable(
            model,
            schema,
            "Zone Thermal Comfort Fanger Model PMV",
            "*",
        )
        _add_output_variable(
            model,
            schema,
            "Zone Thermal Comfort Fanger Model PPD",
            "*",
        )

    for schedule_name in (*reference_schedules, *actuated_schedules):
        _add_output_variable(
            model,
            schema,
            "Schedule Value",
            schedule_name,
            label=f"EcoLoop Schedule Value {schedule_name}",
        )

    meter_type = "Output:Meter"
    schema.require_fields(meter_type, ("key_name", "reporting_frequency"))
    meters = _instances(model, meter_type)
    for meter_name in _OUTPUT_METERS:
        fields = {"key_name": meter_name, "reporting_frequency": "Timestep"}
        schema.validate_instance_fields(meter_type, fields)
        meters[f"EcoLoop {meter_name}"] = fields

    sqlite_type = "Output:SQLite"
    if schema.has_object(sqlite_type):
        valid = schema.field_names(sqlite_type)
        field = "option_type" if "option_type" in valid else None
        if field:
            sqlite = _instances(model, sqlite_type)
            sqlite["EcoLoop SQLite"] = {field: "SimpleAndTabular"}


def _enable_fanger_when_supported(
    model: dict[str, Any],
    schema: SchemaNavigator,
) -> tuple[int, dict[str, str]]:
    object_type = "People"
    if not schema.has_object(object_type):
        return 0, {}
    valid = schema.field_names(object_type)
    comfort_fields = [
        field
        for field in (
            "thermal_comfort_model_1_type",
            "thermal_comfort_model_2_type",
            "thermal_comfort_model_3_type",
            "thermal_comfort_model_4_type",
            "thermal_comfort_model_5_type",
            "thermal_comfort_model_6_type",
            "thermal_comfort_model_7_type",
        )
        if field in valid
    ]
    if not comfort_fields:
        return 0, {}
    prerequisite_fields = (
        "activity_level_schedule_name",
        "clothing_insulation_schedule_name",
        "air_velocity_schedule_name",
        "work_efficiency_schedule_name",
        "clothing_insulation_calculation_method",
        "mean_radiant_temperature_calculation_type",
    )
    schema.require_fields(object_type, prerequisite_fields)
    schema.require_fields(
        "Schedule:Constant",
        ("schedule_type_limits_name", "hourly_value"),
    )
    type_limits = _instances(model, "ScheduleTypeLimits")
    for type_name, type_fields in _FANGER_TYPE_LIMITS.items():
        schema.validate_instance_fields("ScheduleTypeLimits", type_fields)
        existing_type = type_limits.get(type_name)
        if existing_type is not None and existing_type != type_fields:
            raise EnergyPlusIntegrationError(
                f"Cannot install Fanger schedule limits {type_name!r}: "
                "the model already defines that name with different fields."
            )
        type_limits[type_name] = copy.deepcopy(type_fields)

    constant_schedules = _instances(model, "Schedule:Constant")
    for schedule_name, value in _FANGER_SCHEDULE_VALUES.items():
        schedule = {
            "schedule_type_limits_name": _FANGER_SCHEDULE_TYPES[schedule_name],
            "hourly_value": value,
        }
        schema.validate_instance_fields("Schedule:Constant", schedule)
        existing = constant_schedules.get(schedule_name)
        if existing is not None and existing != schedule:
            raise EnergyPlusIntegrationError(
                f"Cannot install Fanger prerequisite schedule {schedule_name!r}: "
                "the model already defines that name with different fields."
            )
        constant_schedules[schedule_name] = schedule

    people = _instances(model, object_type)
    enabled = 0
    people_zone_map: dict[str, str] = {}
    for people_name, fields in people.items():
        activity = fields.get("activity_level_schedule_name")
        if not isinstance(activity, str) or not activity:
            continue
        zone_name = fields.get("zone_or_zonelist_or_space_or_spacelist_name")
        if isinstance(zone_name, str) and zone_name:
            people_zone_map[people_name] = zone_name
        fields.setdefault(
            "work_efficiency_schedule_name",
            "EcoLoop Work Efficiency",
        )
        if not fields.get("clothing_insulation_schedule_name"):
            fields["clothing_insulation_schedule_name"] = "EcoLoop Summer Office Clothing"
            fields["clothing_insulation_calculation_method"] = "ClothingInsulationSchedule"
        else:
            fields.setdefault(
                "clothing_insulation_calculation_method",
                "ClothingInsulationSchedule",
            )
        fields.setdefault("air_velocity_schedule_name", "EcoLoop Air Velocity")
        fields.setdefault(
            "mean_radiant_temperature_calculation_type",
            "EnclosureAveraged",
        )
        if not all(
            isinstance(fields.get(item), str) and fields[item] for item in prerequisite_fields
        ):
            continue
        if not any(
            isinstance(fields.get(item), str) and fields[item].casefold() == "fanger"
            for item in comfort_fields
        ):
            empty_field = next(
                (field for field in comfort_fields if not fields.get(field)),
                None,
            )
            if empty_field is None:
                continue
            fields[empty_field] = "Fanger"
        schema.validate_instance_fields(object_type, fields)
        enabled += 1
    return enabled, people_zone_map


def _has_fanger_people(model: Mapping[str, Any]) -> bool:
    people = model.get("People")
    if not isinstance(people, Mapping):
        return False
    return any(
        isinstance(fields, Mapping)
        and any(
            isinstance(value, str)
            and field.startswith("thermal_comfort_model_")
            and value.casefold() == "fanger"
            for field, value in fields.items()
        )
        for fields in people.values()
    )


def _patch_period_and_timestep(
    model: dict[str, Any],
    schema: SchemaNavigator,
    period: PeriodProtocol,
    timestep_minutes: int,
) -> None:
    if 60 % timestep_minutes:
        raise EnergyPlusIntegrationError(
            f"Zone timestep {timestep_minutes} minutes does not divide one hour."
        )
    run_period_fields = {
        "begin_month": int(period.start_month),
        "begin_day_of_month": int(period.start_day),
        "end_month": int(period.end_month),
        "end_day_of_month": int(period.end_day),
    }
    schema.require_fields("RunPeriod", run_period_fields)
    run_periods = _instances(model, "RunPeriod")
    if not run_periods:
        run_periods["EcoLoop Run Period"] = {}
    selected_name = sorted(run_periods, key=str.casefold)[0]
    selected_fields = run_periods[selected_name]
    run_periods.clear()
    selected_fields.update(run_period_fields)
    run_periods["EcoLoop Evaluation Period"] = selected_fields

    timestep_type = "Timestep"
    schema.require_fields(timestep_type, ("number_of_timesteps_per_hour",))
    timesteps = _instances(model, timestep_type)
    if not timesteps:
        timesteps["EcoLoop Timestep"] = {}
    for fields in timesteps.values():
        fields["number_of_timesteps_per_hour"] = 60 // timestep_minutes


def patch_model(
    source_epjson: Mapping[str, Any],
    schema: SchemaNavigator,
    period: PeriodProtocol,
    timestep_minutes: int,
    *,
    controlled: bool,
) -> tuple[dict[str, Any], dict[str, Any]]:
    """Return one prepared baseline or controlled epJSON model and metadata."""

    model = copy.deepcopy(dict(source_epjson))
    _patch_period_and_timestep(model, schema, period, timestep_minutes)
    (
        reference_heating,
        reference_cooling,
        actuated_heating,
        actuated_cooling,
        thermostat_count,
    ) = _install_baseline_schedules(model, schema, controlled=controlled)
    fanger_people, fanger_people_zone_map = _enable_fanger_when_supported(
        model,
        schema,
    )
    _add_outputs(
        model,
        schema,
        (reference_heating, reference_cooling),
        (actuated_heating, actuated_cooling),
        include_fanger=_has_fanger_people(model),
    )
    metadata = {
        "controlled": controlled,
        "reference_heating_schedule": reference_heating,
        "reference_cooling_schedule": reference_cooling,
        "actuated_heating_schedule": actuated_heating,
        "actuated_cooling_schedule": actuated_cooling,
        "thermostat_objects_patched": thermostat_count,
        "people_objects_fanger_enabled": fanger_people,
        "fanger_prerequisite_schedules": dict(_FANGER_SCHEDULE_VALUES),
        "fanger_people_zone_map": fanger_people_zone_map,
        "fanger_assumptions": {
            "work_efficiency": ("0.0 dimensionless external work for sedentary office activity"),
            "clothing_insulation": "0.5 clo summer office ensemble",
            "air_velocity": "0.1 m/s still-air office assumption",
            "mean_radiant_temperature": "EnclosureAveraged",
        },
    }
    return model, metadata


def _write_json(path: Path, payload: Mapping[str, Any]) -> None:
    path.write_text(
        json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )


def _sha256_model_text(path: Path) -> str:
    """Hash UTF-8 model text after canonicalizing every line ending to LF."""

    text = path.read_text(encoding="utf-8")
    canonical = text.replace("\r\n", "\n").replace("\r", "\n")
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _sha256_file(path: Path) -> str:
    """Hash an artifact exactly as written."""

    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _portable_repository_path(path: Path) -> str:
    """Return a portable repository path, or only a non-repository basename."""

    resolved = path.resolve()
    root = repository_root().resolve()
    try:
        return resolved.relative_to(root).as_posix()
    except ValueError:
        return resolved.name


def _portable_provenance_payload(
    provenance: ModelProvenance,
    repository_model: Path,
) -> dict[str, Any]:
    """Serialize model origin without embedding a developer-machine path."""

    root_license = repository_root() / "models" / "base" / "ENERGYPLUS_LICENSE.txt"
    license_name = (
        _portable_repository_path(root_license)
        if root_license.is_file()
        else provenance.license_path.name
        if provenance.license_path is not None
        else None
    )
    return {
        "repository_model": _portable_repository_path(repository_model),
        "repository_model_sha256": _sha256_model_text(repository_model),
        "repository_model_sha256_mode": "utf-8-text-lf-normalized",
        "source_name": provenance.source_name,
        "source_identity": provenance.source_path.name,
        "energyplus_version": provenance.energyplus_version,
        "energyplus_distribution": (
            f"EnergyPlus {provenance.energyplus_version}; installation is "
            "discovered locally at runtime"
        ),
        "license_path": license_name,
        "selection_reasons": list(provenance.selection_reasons),
    }


def _license_path(installation: EnergyPlusInstallation) -> Path | None:
    for name in ("LICENSE.txt", "LICENSE", "COPYING.txt", "Copyright.txt"):
        path = installation.home / name
        if path.is_file():
            return path.resolve()
    return None


def _copy_model_source(
    installation: EnergyPlusInstallation,
    source: Path,
    destination: Path,
) -> None:
    """Copy a normal IDF or officially expand an HVAC-template example."""

    text = source.read_text(encoding="utf-8", errors="replace").casefold()
    if "hvactemplate:" not in text:
        shutil.copy2(source, destination)
        return
    if installation.expand_objects is None or installation.idd is None:
        raise EnergyPlusIntegrationError(
            "The selected example contains HVACTemplate objects, but ExpandObjects "
            "or the version-matched Energy+.idd is unavailable."
        )
    with tempfile.TemporaryDirectory(prefix="ecoloop-expand-") as temporary:
        work = Path(temporary)
        shutil.copy2(source, work / "in.idf")
        shutil.copy2(installation.idd, work / "Energy+.idd")
        try:
            completed = subprocess.run(  # noqa: S603 - official fixed tool path
                [str(installation.expand_objects)],
                cwd=work,
                capture_output=True,
                check=False,
                text=True,
                timeout=120,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise EnergyPlusIntegrationError(
                f"ExpandObjects could not process {source}: {exc}"
            ) from exc
        expanded = work / "expanded.idf"
        if completed.returncode != 0 or not expanded.is_file():
            diagnostic = "\n".join(
                value.strip() for value in (completed.stdout, completed.stderr) if value.strip()
            )
            raise EnergyPlusIntegrationError(
                f"ExpandObjects failed for {source} (exit {completed.returncode}). "
                f"Output: {diagnostic or 'no diagnostic output'}"
            )
        shutil.copy2(expanded, destination)


def _copy_or_select_source(
    installation: EnergyPlusInstallation,
    configured_path: Path,
    source: Path | None,
) -> tuple[Path, ModelProvenance]:
    configured_path.parent.mkdir(parents=True, exist_ok=True)
    if source is not None:
        selected_path = source.expanduser().resolve()
        if not selected_path.is_file():
            raise EnergyPlusIntegrationError(
                f"Configured source model does not exist: {selected_path}"
            )
        reasons: tuple[str, ...] = ("explicit source model",)
    elif configured_path.is_file():
        selected_path = configured_path.resolve()
        reasons = ("existing version-controlled base model",)
    else:
        candidate = select_official_example(installation)
        selected_path = candidate.path
        reasons = candidate.reasons
    provenance = ModelProvenance(
        source_path=selected_path,
        source_name=selected_path.name,
        energyplus_version=installation.version or "unknown",
        energyplus_home=installation.home,
        license_path=_license_path(installation),
        selection_reasons=reasons,
    )
    if selected_path != configured_path.resolve():
        _copy_model_source(installation, selected_path, configured_path)
    return configured_path.resolve(), provenance


